const assert = require('assert')
const {fen, yuan, id} = require('../utils/admin-pay/wallet')
assert.strictEqual(fen('0.01'),1)
assert.strictEqual(fen('12.3'),1230)
assert.strictEqual(fen('21474836.47'),2147483647)
assert.throws(()=>fen('21474836.48'))
assert.strictEqual(yuan(-123),'-1.23')
assert.throws(()=>fen('1.001'))
assert.throws(()=>fen('-1'))
assert.strictEqual(yuan(123), '1.23')
assert.strictEqual(yuan(undefined), '未读取')
assert.strictEqual(id('9007199254740993'),'9007199254740993')
assert.throws(()=>id(9007199254740992))
console.log('admin-pay wallet amount and ID checks passed')
