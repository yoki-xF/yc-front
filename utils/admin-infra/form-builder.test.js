const assert=require('node:assert/strict'),model=require('./form-builder')
assert.throws(()=>model.parse('[{"type":"input","field":"a"},{"type":"input","field":"a"}]','规则'),/重复/)
assert.throws(()=>model.parse('[{"type":"input","field":"__proto__"}]','规则'),/字段名/)
const rules=[{type:'input',field:'a',title:'名称',validate:[{max:50}],props:{custom:{keep:true}}},{type:'customPlugin',field:'b',script:'preserve, never execute'}]
let changed=model.change(JSON.stringify(rules),0,'required');assert.equal(changed[0].validate.length,2);assert.deepEqual(changed[0].props,rules[0].props)
changed=model.change(JSON.stringify(changed),0,'required');assert.deepEqual(changed[0].validate,[{max:50}])
changed=model.change(JSON.stringify(rules),0,'down');assert.equal(changed[0].field,'b');assert.equal(changed[0].script,rules[1].script)
assert.equal(model.preview(changed)[0].supported,false)
assert.throws(()=>model.change(JSON.stringify(rules),99,'remove'),/位置/)
assert.equal(model.change(JSON.stringify(rules),0,'remove').length,1)
assert.equal(model.preview([{type:'select',options:[{label:'一',value:1},{label:'二',value:'2'},{label:'非法',value:{}}]}])[0].options.length,2)
console.log('Native form builder preserves plugin configuration, validates fields, reorders controls and toggles required rules')
